"""Generate unrestricted relic definitions and the effect/price table."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
spec=json.loads((root/'Docs/Items50.json').read_text(encoding='utf-8'))
items=spec['items'];q=lambda value:json.dumps(value,ensure_ascii=False)
assert len(items)==50 and len({i['id'] for i in items})==50
assert all('owner' not in i for i in items)
assert sum(i['theme'] is None for i in items)==42
for theme in ['ruins','fire','frost','void']:assert sum(i['theme']==theme for i in items)==2
rows=[]
for i in items:
 assert i['buyPrice']>i['sellPrice']>=0 and i['sellPrice']==i['buyPrice']//2
 rows.append('new ItemDefinition('+','.join([q(i['id']),q(i['name']),q(i['effect']),str(i['tier']),str(i['buyPrice']),q(i['theme']),q(i['synergy']),str(i['growthCap'])])+')')
code='''// Generated by Tools/GenerateItem50Catalog.py.
using System;
using System.Collections.Generic;
using System.Linq;
namespace Brodun {
public static class Item50Catalog {
 public static readonly IReadOnlyList<ItemDefinition> All=Array.AsReadOnly(new[]{ROWS});
 static readonly Dictionary<string,ItemDefinition> byId=All.ToDictionary(i=>i.Id);
 public static ItemDefinition Find(string id)=>id!=null&&byId.TryGetValue(id,out var item)?item:null;
 public static IEnumerable<ItemDefinition> Available(string theme)=>All.Where(i=>i.ThemeId==null||i.ThemeId==theme);
}}
'''.replace('ROWS',',\n'.join(rows))
(root/'Assets/BRODUN/Scripts/Rules/Item50Catalog.cs').write_text(code,encoding='utf-8')
