"""Regenerate the Unity-independent catalog: python Tools/GenerateCard70Catalog.py"""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
spec=json.loads((root/'Docs/Cards70.json').read_text(encoding='utf-8'))
if any(c['element']=='독' and c['owner']!='neutral' for c in spec['cards']):
 raise ValueError('Poison cards must belong to the neutral/shared pool.')
if any(c['element'] not in {None,'독'} and c['owner']!='mage' for c in spec['cards']):
 raise ValueError('Non-poison elemental cards must belong to Mage.')
q=lambda s:json.dumps(s,ensure_ascii=False)
elements={None:'None','불':'Fire','물':'Water','얼음':'Ice','번개':'Lightning','바람':'Wind','독':'Poison'}
rarity={'기본':'Starter','하급':'Low','중급':'Middle','상급':'High'}
upgrade_cost={'W13':1,'W14':1,'W15':0,'W16':2,'W17':1,'M09':2,'M15':1,'P08':1,'P13':1,'P14':1,'P15':2,'P16':2,'P17':0,'N11':0,'N13':1,'N14':1,'N15':0,'N16':0}
retained={'W16','W18','M09','M17','P15','P16'}
rows=[]
for c in spec['cards']:
 cost=0 if c['cost']=='X' else c['cost'];upcost=upgrade_cost.get(c['id'],cost)
 owner='null' if c['owner']=='neutral' else 'CharacterId.'+c['owner'].title()
 bonus=('\n원소: '+c['elementEffect']) if c['elementEffect'] else ''
 desc='(up?'+q(c['implementedUpgradeEffect']+bonus)+':'+q(c['effect']+'\n강화: '+c['upgrade']+bonus)+')'
 flags=','.join(str(v).lower() for v in [c['selfExhaust'],c['id'] in retained,c['cost']=='X'])
 rows.append('case '+q(c['id'])+': return new CardDefinition(id,'+q(c['name'])+'+(up?"+":""),'+desc+',up?'+str(upcost)+':'+str(cost)+',ElementType.'+elements[c['element']]+',new CardEffect[0]).Configure('+owner+',CardType.'+c['type']+',CardRarity.'+rarity[c['rarity']]+','+flags+',up?1:0);')
description={'warrior':'힘을 단련해 패왕참을 쓰거나, 남은 방어도를 축적해 성채 붕괴로 마무리합니다.','mage':'원소 카드를 사용해 공명을 모으거나, 활동력을 집중해 고비용 비전을 사용합니다.','priest':'낙인을 축적해 심판하거나, 실제 회복으로 은총을 쌓아 공격과 방어에 사용합니다.'}
heroes=[]
for owner,deck in spec['startingDecks'].items():
 k='CharacterId.'+owner.title();heroes.append('new CharacterDefinition('+k+',legacy.Character('+k+').Name,'+q(description[owner])+',legacy.Character('+k+').MaxHP,3,new[]{'+','.join(map(q,deck))+'})')
code='''// Generated by Tools/GenerateCard70Catalog.py from Docs/Cards70.json.
using System;
using System.Linq;
namespace Brodun {
public static class Card70Catalog {
 public static readonly string[] Ids = new[]{IDS};
 public static GameDefinitions Apply(GameDefinitions legacy) => new GameDefinitions(Ids.Select(id=>Card(id)),new[]{HEROES},legacy.Enemies,new BattleConfig(4,6,legacy.Config.WeakReduction,legacy.Config.FloorHPStep,legacy.Config.EventHeal,legacy.Config.EventGold),legacy.Reward,legacy.Elements.Where(e=>e.Id!=ElementType.Earth&&e.Id!=ElementType.Stone&&e.Id!=ElementType.Explosion));
 public static CardDefinition Card(string id,bool up=false) {switch(id){
ROWS
default:throw new ArgumentException("Unknown card: "+id);}}
}}
'''.replace('IDS',','.join(q(c['id']) for c in spec['cards'])).replace('HEROES',','.join(heroes)).replace('ROWS','\n'.join(rows))
(root/'Assets/BRODUN/Scripts/Rules/Card70Catalog.cs').write_text(code,encoding='utf-8')
